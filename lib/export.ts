/**
 * Prints the analysis
 */
export function printAnalysis(analysis: Analysis) {
  const content = generateTextReport(analysis);
  const printWindow = window.open('', '_blank');
  if (printWindow) {
    // SAFE: Use textContent instead of document.write
    printWindow.document.body.style.fontFamily = 'monospace';
    printWindow.document.body.style.whiteSpace = 'pre-wrap';
    // Create pre element and use textContent (no HTML injection)
    const pre = printWindow.document.createElement('pre');
    pre.textContent = content;
    pre.style.margin = '20px';
    printWindow.document.body.appendChild(pre);
    printWindow.document.close();
    printWindow.print();
  }
}

/**
 * Copies analysis to clipboard
 */
export async function copyAnalysisToClipboard(analysis: Analysis) {
  const content = generateTextReport(analysis);
  try {
    await navigator.clipboard.writeText(content);
    return true;
  } catch (error) {
    console.error('Error copying to clipboard:', error);
    return false;
  }
}

